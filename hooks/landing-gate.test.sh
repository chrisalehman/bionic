#!/bin/bash
# Tests for hooks/landing-gate.sh — THE LANDING SWEEP (epic-16 wave-03, slice T4c/T4d).
#
# Stop. The gate used to run on SubagentStop and judge the ONE agent that stopped. That
# event is structurally invisible to a skill-frontmatter registration (T4b §3: skill hooks
# live in `appState.sessionHooks` keyed by SESSION id, and every subagent-context event is
# dispatched under the SUBAGENT's id, which has no entry there), so the wall was inert the
# moment registration moved into SKILL.md. It now runs on `Stop`, which IS delivered to the
# skill channel, fires once per orchestrator turn, and — the fact that makes the latency a
# non-issue — is GENERATED BY a background agent's landing, which wakes a fresh turn that
# closes 2.5–3.7 s later (T4b §2.3, §4).
#
# The shape that replaces "judge the stopping agent" is a SWEEP: every roster row whose
# `agent_id` is absent from the payload's `background_tasks[]` has landed, and each one is
# verdicted exactly once, ever.
#
# Governing evidence: .bionic/docs/record/session-20260814-wave-detector-terminal-state/
# t4b-probe-report.md §6 (the ratified mechanism), §2–§4 (its evidence).
#
# HERMETIC. Every payload is crafted and piped straight into the gate; nothing here stops a
# real subagent, touches the live installed hooks, or depends on a live wave. Repos are
# throwaway `git init`s under a mktemp'd sandbox, and the roster/plan fixtures are written
# as files.
#
# THE SWEEPER IS REAL IN EVERY CASE THAT HAS ONE. The gate consumes
# `session-sweeper.sh verdict <name>` and never re-implements its predicate, so a stubbed
# verdict would leave exactly the seam this slice exists to close (rule: seam-blindness —
# a seam substituting the value-under-test leaves the production path unverified). The gate
# resolves the sweeper as its own SIBLING, which is what bootstrap's `hooks/*.sh` install
# produces, so Section 6 gets its absent/erroring sweeper by running a COPY of the gate out
# of a directory holding a different sibling — no env override, no PATH seam.
#
# Usage: bash hooks/landing-gate.test.sh

set -uo pipefail

HOOKS_DIR="$(cd "$(dirname "$0")" && pwd)"
GATE="$HOOKS_DIR/landing-gate.sh"

SANDBOX="$(cd "$(mktemp -d "${TMPDIR:-/tmp}/landing-gate-test.XXXXXX")" && pwd)"
BG_PIDS=""
cleanup() {
  local p
  for p in $BG_PIDS; do kill -9 "$p" 2>/dev/null; done
  chmod -R u+rwX "$SANDBOX" 2>/dev/null
  rm -rf "$SANDBOX"
}
trap cleanup EXIT

PASS=0
FAIL=0
TOTAL=0

ok() { TOTAL=$((TOTAL + 1)); PASS=$((PASS + 1)); echo "PASS: $1"; }
no() { TOTAL=$((TOTAL + 1)); FAIL=$((FAIL + 1)); echo "FAIL: $1"; [ -n "${2:-}" ] && echo "      $2"; return 0; }

expect_status()   { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "expected exit $2, got $3"; fi; }
expect_contains() { if printf '%s' "$3" | grep -qF -- "$2"; then ok "$1"; else no "$1" "missing [$2] in: $(printf '%s' "$3" | head -3)"; fi; }
expect_absent()   { if printf '%s' "$3" | grep -qF -- "$2"; then no "$1" "unexpectedly present: $2"; else ok "$1"; fi; }
expect_empty()    { if [ -z "$2" ]; then ok "$1"; else no "$1" "expected no output, got: $2"; fi; }
expect_eq()       { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "expected [$2] got [$3]"; fi; }
expect_gt()       { if [ "$2" -gt "$3" ] 2>/dev/null; then ok "$1"; else no "$1" "expected > $3, got $2"; fi; }
expect_lt()       { if [ "$2" -lt "$3" ] 2>/dev/null; then ok "$1"; else no "$1" "expected < $3, got $2"; fi; }
section()         { printf '\n=== %s ===\n' "$1"; }

