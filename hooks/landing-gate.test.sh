expect_contains "3c: …naming the landed row" "landed-one" "$OUT_STDERR"
expect_absent "3c: …and never the row still in flight" "flying-one" "$OUT_STDERR"
expect_eq "3c: …with one marker, for the landed row alone" "1" "$(swept_count "$R3C")"

# ================================================================= Section 4
section "Section 4: relevance and ambiguity — every way out is silent"

R4="$(make_wave_repo r4)"
add_row "$R4" name=w1-s5 agent_id="$AID_A" deliverable=.bionic/docs/record/never.md \
  launched_at="$(iso_ago 600)"

# A SubagentStop whose id belongs to a SUBAGENT row is not this arm's business either: the
# roster's responsibility partition gives async dispatches to the Stop-sweep, which judges
# them by disappearance from `background_tasks[]`, and teammates to the SubagentStop arm.
# Verdicting here would not merely duplicate the sweep — it would STEAL the refusal, since
# the marker this arm writes is what tells the sweep a row is answered for, and the sweep's
# refusal is the one that reaches the orchestrator (Section 12's rationale).
run_gate "$GATE" "$(substop_payload "$R4" "$SID" "$AID_A" general-purpose false)"
expect_status "4a: a SubagentStop over a SUBAGENT row belongs to the sweep — pass" "0" "$RC"
expect_empty "4a: …silently" "$OUT_STDERR"
expect_eq "4a: …and nothing is swept out from under the sweep" "0" "$(swept_count "$R4")"

run_gate "$GATE" "$(stop_payload "" "$SID" false)"
expect_status "4b: no cwd — the repo is unresolvable, pass" "0" "$RC"

run_gate "$GATE" "$(stop_payload "$SANDBOX/not-a-repo" "$SID" false)"
expect_status "4c: a cwd outside any repo passes" "0" "$RC"

run_gate "$GATE" "$(stop_payload "$R4" "" false)"
expect_status "4d: no session key — no roster to scope to, pass" "0" "$RC"

run_gate "$GATE" "$(stop_payload "$R4" "$SID_B" false)"
expect_status "4e: another session's Stop reads that session's (absent) roster, pass" "0" "$RC"

run_gate "$GATE" "not json at all"
expect_status "4f: an unparseable payload passes" "0" "$RC"

R4B="$(make_repo r4b)"
plan_active "$R4B"
run_gate "$GATE" "$(stop_payload "$R4B" "$SID" false)"
expect_status "4g: no roster file at all passes" "0" "$RC"

# THE UNJOINABLE ROW. `agent_id=` is empty until hooks/execution-recorder.sh's roster arm
# completes the launch row, and a row that never got one cannot be placed on either side of
# the landed/live line. Judging it would hold an agent to a contract on the strength of a
# field we do not have; the ambiguity direction is the same as every other one here.
R4C="$(make_wave_repo r4c)"
add_row "$R4C" name=never-spawned agent_id= status=intended \
  deliverable=.bionic/docs/record/never.md launched_at="$(iso_ago 600)"
run_gate "$GATE" "$(stop_payload "$R4C" "$SID" false)"
expect_status "4h: a row with no agent_id cannot be placed — pass" "0" "$RC"
expect_empty "4h: …silently, claiming nothing about a dispatch that may never have spawned" \
  "$OUT_STDERR"
expect_eq "4h: …and is not marked swept, so a later identification still gets its verdict" \
  "0" "$(swept_count "$R4C")"

# THE MONOTONE SEQUENCE ITSELF (t6-review.md F-3 sub-gap): `intended` (agent_id empty) then
# `identified` (agent_id filled) for the SAME contract, appended as two roster rows the way
# hooks/dispatch-preflight.sh and hooks/execution-recorder.sh really write them — the
# two-row lifecycle the monotone `if (aid != "") agent[name] = aid` rule exists for. 4h
# drove an all-empty row; 8c (below) drives two ALREADY-filled duplicate rows; neither drove
# the TRANSITION. Subagent-shaped (no `teammate_id=`), so this is the sweep's row, not the
# SubagentStop arm's (session-20260815 T2 teammate-skip).
R4I="$(make_wave_repo r4i)"
add_row "$R4I" name=w4-t2mono status=intended agent_id= \
  deliverable=.bionic/docs/record/never-mono.md tool_use_id=toolu_MONO \
  launched_at="$(iso_ago 600)"
add_row "$R4I" name=w4-t2mono status=identified agent_id="$AID_A" \
  deliverable=.bionic/docs/record/never-mono.md tool_use_id=toolu_MONO \
  launched_at="$(iso_ago 600)"
run_gate "$GATE" "$(stop_payload "$R4I" "$SID" false)"
