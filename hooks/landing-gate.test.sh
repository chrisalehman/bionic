make_repo() {  # <label> -> repo path
  local r="$SANDBOX/$1"
  mkdir -p "$r/.bionic/tmp"
  ( cd "$r" && git init -q . 2>/dev/null )
  printf '%s' "$r"
}

# The standard fixture: an active wave, a roster, and nothing delivered.
make_wave_repo() {  # <label> -> repo path
  local r
  r="$(make_repo "$1")"
  plan_active "$r"
  new_roster "$r"
  printf '%s' "$r"
}

deliver() {  # <repo> <relative path> — a real artifact, written now (after launched_at)
  local p="$1/$2"
  mkdir -p "$(dirname "$p")"
  printf 'the report\n' > "$p"
}

# ---------- running the gate ----------
#
# Sets OUT_STDOUT / OUT_STDERR / RC. Bounded: a gate that hangs inside a Stop hook is a
# defect, and a suite that hangs on it would wedge `bash tests/run.sh`.
run_gate() {  # <gate path> <payload json>
  local gate="$1" json="$2"
  printf '%s' "$json" > "$SANDBOX/payload.json"
  ( exec bash "$gate" < "$SANDBOX/payload.json" ) \
    > "$SANDBOX/gate.out" 2> "$SANDBOX/gate.err" &
  local pid=$!
  BG_PIDS="$BG_PIDS $pid"
  local waited=0
  while kill -0 "$pid" 2>/dev/null && [ "$waited" -lt 200 ]; do
    sleep 0.1; waited=$((waited + 1))
  done
  if kill -0 "$pid" 2>/dev/null; then
    kill -9 "$pid" 2>/dev/null
    RC=124
  else
    wait "$pid"; RC=$?
  fi
  OUT_STDOUT="$(cat "$SANDBOX/gate.out")"
  OUT_STDERR="$(cat "$SANDBOX/gate.err")"
}

REFUSAL_TAIL="Land the contract (write the named artifacts), or stop again to pass — this gate blocks once."

# ================================================================= Section 1
section "Section 1: a LANDED row with an unmet contract refuses the turn's end"

R1="$(make_wave_repo r1)"
add_row "$R1" name=w1-s5 agent_id="$AID_A" deliverable=.bionic/docs/record/never.md \
  launched_at="$(iso_ago 600)"

# No live task carries this agent's id, so it has landed — which is the whole of the
# landed/live discrimination (T4b §2.2: background_tasks answers "who is still running",
# never "who ran and finished").
run_gate "$GATE" "$(stop_payload "$R1" "$SID" false)"
expect_status "1a: a landed UNMET contract refuses the stop (exit 2)" "2" "$RC"
expect_contains "1a: the refusal opens with the contract verdict" \
  "LANDING CONTRACT UNMET" "$OUT_STDERR"
expect_contains "1a: …names the ROW, because a sweep judges rows and not the caller" \
  "w1-s5" "$OUT_STDERR"
expect_contains "1a: …names the artifact that is not on disk" \
  "missing=.bionic/docs/record/never.md" "$OUT_STDERR"
expect_contains "1a: …and tells the reader how to pass" "$REFUSAL_TAIL" "$OUT_STDERR"
expect_empty "1a: the refusal goes to stderr, never stdout" "$OUT_STDOUT"

# IDEMPOTENT. Stop fires once per orchestrator TURN and a landed row stays landed forever,
# so a gate that re-verdicted would refuse every turn end for the rest of the session over
# one agent's failure — the false-alarm shape this machinery exists to end.
run_gate "$GATE" "$(stop_payload "$R1" "$SID" false)"
expect_status "1b: the SAME row is not verdicted twice — the second Stop passes" "0" "$RC"
expect_empty "1b: …silently on stdout" "$OUT_STDOUT"
expect_empty "1b: …and on stderr" "$OUT_STDERR"
expect_eq "1b: …and exactly one marker was written, not two" "1" "$(swept_count "$R1")"
expect_contains "1b: …naming the agent id it closed" "agent_id=$AID_A" "$(swept_lines "$R1")"
expect_contains "1b: …and the state it recorded" "state=UNMET" "$(swept_lines "$R1")"

# BLOCKS ONCE on re-entry too: Claude Code re-enters the stop with stop_hook_active true
# after a hook blocked it, and a gate that refused again would wedge the turn.
R1B="$(make_wave_repo r1b)"
add_row "$R1B" name=w1-s5 agent_id="$AID_A" deliverable=.bionic/docs/record/never.md \
  launched_at="$(iso_ago 600)"
run_gate "$GATE" "$(stop_payload "$R1B" "$SID" true)"
expect_status "1c: stop_hook_active true passes the same unmet contract" "0" "$RC"
expect_empty "1c: …silently" "$OUT_STDERR"
expect_eq "1c: …and takes no verdict at all, so the row is still owed one" \
  "0" "$(swept_count "$R1B")"

# ================================================================= Section 2
section "Section 2: a landed row that DID deliver is closed, silently"

