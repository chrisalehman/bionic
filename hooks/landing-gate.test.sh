#
# FIXTURE FIDELITY (declared per rule fixtures-can-pin-away-the-test).
#
#   * Stop payload ENVELOPE — VERBATIM key set from t4b-probe-report.md §2.1, a live Stop
#     captured 2026-08-15 (CLI 2.1.233): background_tasks, cwd, effort, hook_event_name,
#     last_assistant_message, permission_mode, prompt_id, session_crons, session_id,
#     stop_hook_active, transcript_path. The `background_tasks[]` row shape is §2.2's
#     verbatim: {id, type, status, description, agent_type}.
#   * agent ids — the transcript form the platform mints for an Agent dispatch
#     (`a8e3d9b517abc6bf7`, §4), which is the SAME string `tool_response.agentId` returns and
#     the SAME string `background_tasks[].id` carries. That triple identity is the join this
#     slice is built on, so the fixtures spell one form and never three.
#   * roster rows — the roster-state/v1 field set and ORDER written by
#     hooks/dispatch-preflight.sh (the `ROW=` assignment), copied from
#     hooks/session-sweeper.test.sh's `mkrow`. This suite's subject reads the roster for the
#     JOIN KEY only; the contract is read by the sweeper, which is the real one here.
#   * SYNTHESIZED and declared: session ids, plan text, deliverable paths, the marker process
#     a STILL-LIVE row claims. None is a platform surface.

SID="3b51bef0-d7bd-447a-bc65-8916c4b25353"
