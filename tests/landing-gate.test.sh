run_gate "$MONODIR/hooks/stop.sh" "$(stop_payload "$R4I_MUT" "$SID" false)"
expect_status "4i-mut: with the guard inverted, the SAME genuinely-UNMET contract passes silently" \
  "0" "$RC"

