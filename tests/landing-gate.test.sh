# ---------- git fixtures for the Files: reconciliation (S18, AC-22) ----------
#
# A REAL WORKTREE, REAL COMMITS, REAL git diff/merge-base — every other fixture in this file
# is a synthesized roster line because the gate's OWN subject (the sweep, the landing verdict)
# never touches git. This one does: the reconciliation IS a git operation, and a fixture that
# faked its answer would leave exactly the production path this task adds unverified (rule:
# seam-blindness — a seam substituting the value under test proves nothing about it).
export GIT_CONFIG_GLOBAL=/dev/null
export GIT_CONFIG_SYSTEM=/dev/null
export GIT_CONFIG_NOSYSTEM=1
export GIT_TERMINAL_PROMPT=0

git_id() { git -C "$1" config user.email "test@example.invalid"; git -C "$1" config user.name "Bionic Test"; }

# The main checkout: one commit on a branch named `main` (forced, so the fixture is
# deterministic regardless of the machine's init.defaultBranch), which is what
# `git -C <repo> rev-parse --abbrev-ref HEAD` — the branch the reconciliation merge-bases
# against — reads back.
make_git_wave_repo() {  # <label> -> repo path
  local r
  r="$(make_wave_repo "$1")"
  git -C "$r" symbolic-ref HEAD refs/heads/main
  git_id "$r"
  printf '.bionic\n.bionic/\n.worktrees/\n' > "$r/.gitignore"
  echo base > "$r/base.txt"
  git -C "$r" add .gitignore base.txt
  git -C "$r" commit -q -m base
  printf '%s' "$r"
}

# A linked worktree at .worktrees/<name>, branched off the repo's current HEAD — the same
# place `worktree_for_row` (payload/scripts/lib/worktree.sh) looks and spawn-worktree.sh
# creates one. <name> doubles as the roster row's `name=` in every case but §16d, so the
# primary (case-preserving) resolution path is what most of this section exercises.
make_slice_tree() {  # <repo> <name> -> worktree path
  local r="$1" name="$2" wt="$1/.worktrees/$2"
  git -C "$r" worktree add -q "$wt" -b "wt/$name" >/dev/null 2>&1
  git_id "$wt"
  printf '%s' "$wt"
}

# THE SAME THING, CUT FROM A NAMED REF rather than the repo's current HEAD (epic-23
# wave-16, REQ-7, AC-7.1): the fixture the B2 shape needs — a tree based on a branch that is
# NOT the main checkout's current one, which every §16 fixture above sidesteps by branching
# off HEAD while the main checkout sits on the same commit.
make_slice_tree_from() {  # <repo> <name> <ref> -> worktree path
  local r="$1" name="$2" ref="$3" wt="$1/.worktrees/$2"
  git -C "$r" worktree add -q "$wt" -b "wt/$name" "$ref" >/dev/null 2>&1
  git_id "$wt"
  printf '%s' "$wt"
}

# One commit in the worktree touching every path given.
commit_files() {  # <worktree> <message> <path>...
  local wt="$1" msg="$2" p
  shift 2
  for p in "$@"; do
    mkdir -p "$(dirname "$wt/$p")"
    echo content >> "$wt/$p"
  done
  git -C "$wt" add "$@"
  git -C "$wt" commit -q -m "$msg"
}

# ---------- running the gate ----------
#
# Sets OUT_STDOUT / OUT_STDERR / RC. Bounded: a gate that hangs inside a Stop hook is a
# defect, and a suite that hangs on it would wedge `bash tests/run.sh`.
# THE ENVIRONMENT AGREES WITH THE PAYLOAD, because on the machine it does (A-probe-2: a
# plain /clear re-keys env, payload and pid file together). Since bionic 1.4.0 the hook
# takes its session id from lib/session.sh, where the env value is primary — so a driver
# that left the runner's own CLAUDE_CODE_SESSION_ID in the environment would be driving a
# DIVERGENCE, not a session, and every roster filename below would be built from the
# wrong key. A payload with no session key exports an empty one, which is what keeps the
# no-session-key arms reaching the fail direction they pin.
GATE_VERBOSE=1
run_gate() {  # <gate path> <payload json>
  local gate="$1" json="$2"
  local _sid; _sid=$(printf '%s' "$json" | jq -r '.session_id // ""' 2>/dev/null) || _sid=""
  printf '%s' "$json" > "$SANDBOX/payload.json"
  # THE KNOB IS A DRIVER SETTING HERE, not a second drive (task 13, ruling D-1). This
  # gate BLOCKS ONCE: it records that it refused and passes on the next stop, so a second
  # invocation to read `detail` comes back empty and every arm asserting the detail would
  # be asserting over nothing. Measured, not assumed. So the one drive carries
  # BIONIC_WALL_VERBOSE=1 by default — `$OUT_STDERR` is then the line PLUS the detail,
  # which is what the per-row arms below read — and the AC-E1.3 section sets
  # GATE_VERBOSE=0 for its own fixtures, where the one line on its own is the subject.
  ( exec env CLAUDE_CODE_SESSION_ID="$_sid" \
      ${GATE_VERBOSE:+BIONIC_WALL_VERBOSE=$GATE_VERBOSE} bash "$gate" < "$SANDBOX/payload.json" ) \
    > "$SANDBOX/gate.out" 2> "$SANDBOX/gate.err" &
  local pid=$!
  BG_PIDS="$BG_PIDS $pid"
  local waited=0
  while kill -0 "$pid" 2>/dev/null && [ "$waited" -lt 200 ]; do
    sleep 0.1; waited=$((waited + 1))
  done
  if kill -0 "$pid" 2>/dev/null; then
    kill -9 "$pid" 2>/dev/null
    RC=124
  else
    wait "$pid"; RC=$?
  fi
  OUT_STDOUT="$(cat "$SANDBOX/gate.out")"
  # THE SWEEP'S OWN HALF OF A SHARED STREAM (epic-23 wave-11, T12). hooks/stop.sh runs
  # four verdicts in one process, so its stderr now carries whatever the other three had
  # to say about the same event. That is not new BEHAVIOUR — all four hooks fired on
  # every Stop before the merge and each wrote its own advisory then too; what is new is
  # that ONE process's stream carries all of it, and this suite used to read a stream
  # only the gate could write. Every "…silently" arm below means the SWEEP said nothing,
  # so the three siblings' advisories are removed here, by their own self-naming prefix,
  # and nothing else is. $OUT_STDERR_RAW keeps the whole stream for any arm that wants it.
  OUT_STDERR_RAW="$(cat "$SANDBOX/gate.err")"
  OUT_STDERR="$(/usr/bin/grep -v -e '^context-spend: ' -e '^patrol-duties-gate: ' \
                                 -e '^patrol-revive: ' "$SANDBOX/gate.err" || true)"
  # THE SAME CALL AGAIN, WITH THE KNOB, ONLY WHEN IT REFUSED (task 13, ruling D-1).
  # This gate's refusal is now ONE line — `bionic: stop refused — <fact> (<fix>)` — and
  # the per-row paragraphs this suite reads for names, files and derived suites are
  # `detail`, which reaches a reader only under BIONIC_WALL_VERBOSE=1. `$OUT_STDERR` is
  # the line; `$OUT_VSTDERR` is the line plus the detail. Gated on the refusal so a
  # PERMITTED stop is never swept twice.
  OUT_VSTDERR="$OUT_STDERR"
}

